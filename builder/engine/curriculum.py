def _check_dag():
    for t in TOPICS.values():
        for p in t.prereqs:
            assert p in TOPICS, f"{t.id}: неизвестный пререквизит {p}"
            assert TOPICS[p].grade <= t.grade, f"{t.id}: пререквизит {p} из более старшего класса"


_check_dag()


@lru_cache(maxsize=None)
def ancestors(tid: str) -> frozenset[str]:
    out: set[str] = set()
    for p in TOPICS[tid].prereqs:
        out.add(p)
        out |= ancestors(p)
    return frozenset(out)


@lru_cache(maxsize=None)
def descendants(tid: str) -> frozenset[str]:
    return frozenset(t.id for t in TOPICS.values() if tid in ancestors(t.id))


def topo_order(ids) -> list[str]:
    """Топологический порядок (сначала база), при равенстве — по классу и порядку объявления."""
    order = list(TOPICS)
    ids = set(ids)
    return sorted(ids, key=lambda i: (len(ancestors(i) & ids), TOPICS[i].grade, order.index(i)))


def target_topics(grade: int, goal: str) -> list[str]:
    """Темы, которые ученик должен уметь к своей цели."""
    if goal == "oge":
        return [t.id for t in TOPICS.values() if "oge" in t.exams and t.grade <= 9]
    if goal == "ege":
        return [t.id for t in TOPICS.values() if "ege" in t.exams]
    return [t.id for t in TOPICS.values() if t.grade == grade] or \
        [t.id for t in TOPICS.values() if t.grade == max(x.grade for x in TOPICS.values() if x.grade <= grade)]


def importance(tid: str, scope: set[str]) -> int:
    """Сколько тем из области интереса опираются на данную тему."""
    return len(descendants(tid) & scope)
